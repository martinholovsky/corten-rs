#!/usr/bin/env python3
"""Writes docs/assets/cwe-rust-corten.svg from audit/applicability/table.csv
(merged by scripts/applicability-table.py). Every number on the chart is
counted here; nothing is typed by hand.

Rows: Rust with `unsafe` allowed; safe Rust; safe Rust + Corten. The Corten
bar shows what is still writable: a solid part (writable even if every claimed
elimination held), a hatched part (claimed eliminations not yet proven by the
corpus, so still counted), and a dashed outline for the verified eliminations.

Usage: scripts/applicability-chart.py [--check]   (run from the repository root)
  --check  exit 1 if the SVG on disk differs from what would be written.
The PNG is rendered separately: rsvg-convert -z 2 docs/assets/cwe-rust-corten.svg
-o docs/assets/cwe-rust-corten.png (needs the Archivo font installed).
"""

import csv
import re
import sys
from pathlib import Path

TABLE = Path("audit/applicability/table.csv")
TOOLCHAIN = Path("rust-toolchain.toml")
SVG = Path("docs/assets/cwe-rust-corten.svg")

X0 = 72  # left edge of every bar
TRACK = 760  # px for all CWEs


def counts() -> dict:
    t = list(csv.DictReader(TABLE.open(newline="")))
    safe = [r for r in t if r["safe_rust"] == "yes"]
    verified = [r for r in safe if r["ledger_bucket"] == "E" and r["ledger_status"] == "verified"]
    claimed = [r for r in safe if r["ledger_bucket"] == "E" and r["ledger_status"] != "verified"]
    return {
        "total": len(t),
        "unsafe": sum(r["unsafe_rust"] == "yes" for r in t),
        "safe": len(safe),
        "verified": len(verified),
        "claimed": len(claimed),
        "corten": len(safe) - len(verified),
        "absent": sum(r["unsafe_rust"] == "no" for r in t),
        "notcode": sum(r["unsafe_rust"] == "n/a" for r in t),
        "programs": sum(r["evidence"] != "none" for r in t),
    }


def rustc() -> str:
    m = re.search(r'^channel\s*=\s*"([^"]+)"', TOOLCHAIN.read_text(), re.M)
    if not m:
        sys.exit(f"no channel in {TOOLCHAIN}")
    return m.group(1)


def render(c: dict, rustc_version: str) -> str:
    def w(n: int) -> float:
        v = round(n * TRACK / c["total"], 1)
        return int(v) if v == int(v) else v

    def x(n: int) -> float:
        return round(X0 + w(n), 1)

    need_unsafe = c["unsafe"] - c["safe"]
    not_rust = c["total"] - c["unsafe"]
    if_claims = c["corten"] - c["claimed"]
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 680" width="1200" height="680" role="img" aria-labelledby="t d">
  <title id="t">CWE weaknesses that can still be written: Rust, safe Rust, safe Rust + Corten</title>
  <desc id="d">Of MITRE CWE 4.20's {c['total']} weaknesses: {c['unsafe']} can be written in Rust with unsafe allowed; {c['safe']} in safe Rust ({need_unsafe} need unsafe); {c['corten']} in safe Rust under Corten ({c['verified']} eliminated, verified by compile-fail tests). {c['claimed']} more eliminations are claimed but not yet proven, so they are still counted; {if_claims} would remain if every claim held.</desc>
  <!-- Generated by scripts/applicability-chart.py from audit/applicability/table.csv;
       do not edit by hand. Scale: {TRACK} px = {c['total']} CWEs. -->
  <defs>
    <path id="shield" d="M50 6 L88 18 V48 C88 72 72 88 50 96 C28 88 12 72 12 48 V18 Z"/>
    <linearGradient id="plate" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#F0A060"/>
      <stop offset="0.55" stop-color="#D2702A"/>
      <stop offset="1" stop-color="#A9481B"/>
    </linearGradient>
    <mask id="cut">
      <rect x="0" y="0" width="100" height="100" fill="#fff"/>
      <path d="M68.4 31.6 A26 26 0 1 0 68.4 68.4" fill="none" stroke="#000" stroke-width="14"/>
    </mask>
    <pattern id="claimed" patternUnits="userSpaceOnUse" width="8" height="8" patternTransform="rotate(45)">
      <rect width="8" height="8" fill="#3A2C25"/>
      <rect width="4" height="8" fill="#D2702A"/>
    </pattern>
  </defs>
  <rect width="1200" height="680" rx="24" fill="#1E1714"/>

  <svg x="64" y="52" width="64" height="64" viewBox="0 0 100 100" aria-hidden="true">
    <use href="#shield" fill="#B5541E"/>
    <use href="#shield" fill="#8B3A1A" transform="translate(50 51) scale(0.84) translate(-50 -51)"/>
    <use href="#shield" fill="#6E2A12" transform="translate(50 51) scale(0.68) translate(-50 -51)"/>
    <use href="#shield" fill="#3A160A" transform="translate(50 51) scale(0.52) translate(-50 -51)"/>
    <g transform="translate(35 34) scale(0.3)"><g mask="url(#cut)"><rect x="6" y="6" width="88" height="88" rx="6" fill="url(#plate)"/></g></g>
  </svg>
  <g font-family="Archivo">
    <text x="144" y="74" font-size="14" font-weight="500" letter-spacing="3" fill="#D2702A">CORTEN · CWE SURFACE</text>
    <text x="144" y="112" font-size="34" font-weight="800" fill="#F6EBDD">Weaknesses you can still write</text>
    <text x="144" y="142" font-size="17" font-weight="500" fill="#CDBFB4">Of MITRE's {c['total']} CWEs: what Rust's compiler, then Corten, take off the table.</text>

    <line x1="72" y1="178" x2="1128" y2="178" stroke="#3A2E28" stroke-width="1"/>

    <!-- Row 1: Rust, unsafe allowed -->
    <text x="72" y="236" font-size="18" font-weight="500" fill="#E9DCCB">Rust, <tspan font-family="monospace" font-size="16">unsafe</tspan> allowed</text>
    <text x="832" y="236" font-size="13" font-weight="500" fill="#A89A90" text-anchor="end">{c['total']} CWEs</text>
    <rect x="72" y="248" width="{TRACK}" height="34" rx="4" fill="#2E2420"><title>MITRE CWE 4.20: {c['total']} weaknesses</title></rect>
    <rect x="72" y="248" width="{w(c['unsafe'])}" height="34" rx="4" fill="#76787C"><title>Rust, unsafe allowed: {c['unsafe']} CWEs</title></rect>
    <text x="848" y="272" font-size="20" font-weight="800" fill="#F6EBDD">{c['unsafe']}</text>
    <text x="900" y="272" font-size="15" font-weight="500" fill="#A89A90">{not_rust} not writable in Rust</text>

    <!-- Row 2: safe Rust -->
    <text x="72" y="336" font-size="18" font-weight="500" fill="#E9DCCB">Safe Rust</text>
    <rect x="72" y="348" width="{TRACK}" height="34" rx="4" fill="#2E2420"/>
    <rect x="72" y="348" width="{w(c['safe'])}" height="34" rx="4" fill="#76787C"><title>Safe Rust: {c['safe']} CWEs</title></rect>
    <rect x="{round(x(c['safe']) + 3, 1)}" y="349" width="{round(w(c['unsafe']) - w(c['safe']) - 4, 1)}" height="32" rx="4" fill="none" stroke="#9A9CA0" stroke-width="2" stroke-dasharray="4 3"><title>{need_unsafe} CWEs need unsafe</title></rect>
    <text x="848" y="372" font-size="20" font-weight="800" fill="#F6EBDD">{c['safe']}</text>
    <text x="900" y="372" font-size="15" font-weight="500" fill="#CDBFB4">−{need_unsafe} need <tspan font-family="monospace" font-size="14">unsafe</tspan></text>

    <!-- Row 3: safe Rust + Corten, highlighted -->
    <rect x="56" y="408" width="1088" height="116" rx="12" fill="#2B1F1A"/>
    <text x="72" y="440" font-size="18" font-weight="800" fill="#F6EBDD">Safe Rust + Corten</text>
    <rect x="72" y="452" width="{TRACK}" height="34" rx="4" fill="#3A2C25"/>
    <rect x="72" y="452" width="{w(if_claims)}" height="34" rx="4" fill="#D2702A"><title>Still writable even if every claimed elimination held: {if_claims} CWEs</title></rect>
    <rect x="{round(x(if_claims) + 2, 1)}" y="452" width="{round(w(c['corten']) - w(if_claims) - 2, 1)}" height="34" rx="4" fill="url(#claimed)"><title>{c['claimed']} CWEs Corten claims to eliminate, not yet proven by the corpus: still counted as writable</title></rect>
    <rect x="{round(x(c['corten']) + 3, 1)}" y="453" width="{round(w(c['safe']) - w(c['corten']) - 4, 1)}" height="32" rx="4" fill="none" stroke="#D2702A" stroke-width="2" stroke-dasharray="4 3"><title>{c['verified']} eliminated by Corten, each verified by a compile-fail test</title></rect>
    <text x="848" y="476" font-size="20" font-weight="800" fill="#F6EBDD">{c['corten']}</text>
    <text x="900" y="476" font-size="15" font-weight="500" fill="#E8873A">−{c['verified']} eliminated, verified</text>
    <rect x="900" y="494" width="14" height="14" rx="2" fill="url(#claimed)"/>
    <text x="922" y="506" font-size="15" font-weight="500" fill="#CDBFB4">{c['claimed']} claimed, not yet proven</text>

    <line x1="72" y1="568" x2="1128" y2="568" stroke="#3A2E28" stroke-width="1"/>
    <g font-size="13" font-weight="500" fill="#A89A90">
      <text x="72" y="594">Per-CWE review of MITRE CWE 4.20 (docs/rust-applicability.md). {c['programs']} answers rest on programs re-checked against rustc {rustc_version}.</text>
      <text x="72" y="616">Not writable in Rust: {c['absent']} need a construct Rust lacks, {c['notcode']} are not code (hardware, physical, process). Hatched: eliminations Corten claims but</text>
      <text x="72" y="638">its compile-fail corpus does not yet prove; {if_claims} would remain if all held. Corten forbids unsafe, so the {need_unsafe} above are gone under it too.</text>
    </g>
  </g>
</svg>
"""


def main() -> int:
    out = render(counts(), rustc())
    if "--check" in sys.argv[1:]:
        if SVG.read_text() != out:
            print(f"{SVG} is stale: run scripts/applicability-chart.py", file=sys.stderr)
            return 1
        return 0
    SVG.write_text(out)
    c = counts()
    print(f"unsafe {c['unsafe']} safe {c['safe']} corten {c['corten']} "
          f"(verified {c['verified']}, claimed {c['claimed']}, if all claims hold {c['corten'] - c['claimed']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
