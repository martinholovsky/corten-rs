#!/usr/bin/env python3
"""Writes docs/rust-comparison.md from audit/applicability/table.csv (merged
by scripts/applicability-table.py), the category notes in
audit/applicability/category-notes.csv, and, for "what changed", the
pre-audit ledger at commit BASELINE. Every number in the doc is counted here.

Usage: scripts/applicability-comparison.py   (run from the repository root)
"""

import collections
import csv
import io
import subprocess
from pathlib import Path

TABLE = Path("audit/applicability/table.csv")
NOTES = Path("audit/applicability/category-notes.csv")
DOC = Path("docs/rust-comparison.md")
# main before the audit: the tag-based classification the review replaced.
BASELINE = "1618fbc42634c645617c09e0f6197aea30eb4407"  # full SHA: CI fetches it by name


def key(r):
    return int(r["cwe_id"].split("-")[1])


def verdict(r):
    return {("yes", "yes"): "applies", ("yes", "no"): "unsafe-rust-only",
            ("no", "no"): "not-applicable", ("n/a", "n/a"): "not-coding"}[(r["unsafe_rust"], r["safe_rust"])]


def main() -> None:
    t = list(csv.DictReader(TABLE.open(newline="")))
    notes = {r["category"]: r for r in csv.DictReader(NOTES.open(newline=""))}
    base_text = subprocess.run(
        ["git", "show", f"{BASELINE}:ledger/cwe-ledger.csv"], capture_output=True, text=True, check=True
    ).stdout
    base = {r["cwe_id"]: r["rust_applicability"] for r in csv.DictReader(io.StringIO(base_text))}

    U = [r for r in t if r["unsafe_rust"] == "yes"]
    S = [r for r in t if r["safe_rust"] == "yes"]
    only = [r for r in U if r["safe_rust"] == "no"]
    absent = [r for r in t if r["unsafe_rust"] == "no"]
    notcode = [r for r in t if r["unsafe_rust"] == "n/a"]

    def verified(r):
        return r["ledger_bucket"] == "E" and r["ledger_status"] == "verified"

    corten = [r for r in S if not verified(r)]
    corten_if_claims = [r for r in S if r["ledger_bucket"] != "E"]
    base_count = sum(v in ("applies", "unsafe-rust-only") for v in base.values())
    moves = collections.Counter((base[r["cwe_id"]], verdict(r)) for r in t)
    hw = moves[("applies", "not-coding")] + moves[("unsafe-rust-only", "not-coding")]
    gone = moves[("applies", "not-applicable")] + moves[("unsafe-rust-only", "not-applicable")]
    to_safe = moves[("unsafe-rust-only", "applies")]
    to_unsafe = moves[("applies", "unsafe-rust-only")]
    nN = sorted((r for r in U if r["ledger_bucket"] == "N"), key=key)
    b = collections.Counter(r["ledger_bucket"] for r in U)
    v_all = sum(verified(r) for r in U)

    rows = []
    for cat, _ in sorted(collections.Counter(r["category"] for r in U).items(), key=lambda kv: (-kv[1], kv[0])):
        cu = [r for r in U if r["category"] == cat]
        cs = [r for r in cu if r["safe_rust"] == "yes"]
        cb = collections.Counter(r["ledger_bucket"] for r in cu)
        n = notes[cat]
        rows.append(
            f"| {cat} | {len(cu)} | {len(cs)} | {len(cu) - len(cs)} | {n['plain_rust_today']} | "
            f"{n['corten_mechanism']} | {cb['E']} / {cb['C']} / {cb['O']} / {cb['N']} | {sum(verified(r) for r in cu)} |"
        )

    def cat_e(cat):
        cu = [r for r in U if r["category"] == cat]
        return sum(r["ledger_bucket"] == "E" for r in cu), len(cu)

    inj_e, inj_n = cat_e("Injection")
    fh_e, fh_n = cat_e("File Handling")

    out = f"""# Corten versus plain Rust: CWE coverage

Generated by `scripts/applicability-comparison.py`; do not edit by hand.

Of the 944 weaknesses in MITRE CWE 4.20, **{len(U)} can be written in Rust** with `unsafe` allowed, **{len(S)} in safe Rust**, and **{len(corten)} in safe Rust under Corten** once its verified eliminations are taken out ({len(S) - len(corten)} of them; {len(corten_if_claims)} would remain if every claimed elimination held). Of the rest, {len(absent)} need a construct Rust does not have and {len(notcode)} are not weaknesses of code (chip and hardware design, physical attacks, process, documentation).

These numbers come from a per-CWE review, recorded with its reasoning in [`rust-applicability.md`](rust-applicability.md) and [`audit/applicability/table.csv`](../audit/applicability/table.csv). Wherever the compiler prevents a weakness, or could plausibly have prevented it, a program in `audit/applicability/` shows the outcome, and `scripts/applicability-check.sh` re-checks every program against stock rustc in CI: {sum(r['evidence'] != 'none' for r in t)} of the 944 rows rest on programs. The remaining rows are logic, design or policy weaknesses that no compiler prevents, or constructs Rust lacks, each with its reasoning. A compiling program shows a weakness can be written; that it exhibits the weakness is the judgement stated in its comment.

Corten's buckets over the {len(U)} that can be written: E {b['E']} / C {b['C']} / O {b['O']} / N {b['N']}, with {v_all} of the E rows verified by compile-fail tests. Read the unverified E rows as targets. The {len(nN)} in N ({", ".join(r['cwe_id'] for r in nN)}) are comment, whitespace and documentation weaknesses the design classed as not coding; the review found them to be source code, as their parent CWE-1078 already is in the ledger. Their bucket is unchanged pending a ledger decision.

## How each CWE was sorted

The first classification (Phase 0) took Rust applicability from each CWE's `Applicable_Platforms` language list in MITRE's data, plus 46 judgement calls. MITRE's tags record where a weakness has been documented, not where a language prevents it, and that rule counted {base_count} for Rust. The per-CWE review replaced it. Each CWE got three answers, with reasoning:

| Question | Answers |
| --- | --- |
| Can a Rust program contain it, `unsafe` allowed (std only; external systems stubbed)? | yes / no / n/a |
| Can safe Rust contain it? | yes / no / n/a |
| What does Corten do? | from the ledger: eliminated (verified or claimed), checkable (C), out of reach (O) |

A weakness counts as code when MITRE names a way software introduces it; one MITRE introduces only in hardware design, requirements or process is n/a. That rule is what separates the transient-execution weaknesses: CWE-1420, 1421 and 1423 can be introduced by software (a sandbox relying on bounds checks, system software skipping state or predictor barriers at context switches) and count; CWE-1037, 1303, 1342 and 1422 are introduced only in processor design and do not.

What changed from the tag-based count (against the ledger at `{BASELINE[:7]}`): {hw} counted for Rust are weaknesses of chip design, hardware, physical attacks or process (now n/a); {gone} counted for Rust need a construct Rust does not have (C-style fall-through, class inheritance, virtual destructors, runtime-named variables); {to_safe} counted as `unsafe`-only can be written in safe Rust (`as` casts that sign-extend or wrap, `chroot`, stale bytes in reused buffers); and {to_unsafe} counted as writable in safe Rust need `unsafe` (reading uninitialised memory, E0381; unsynchronised mutable statics; signal handlers). Measured rather than recalled: std opens files, sockets and pipes close-on-exec (a child process saw no new descriptor on macOS and Linux).

## By category

Counts are over the weaknesses that can be written in Rust. "Plain Rust today" is a summary of what the stable language and standard library do for the category on their own; the per-CWE answers are in [`rust-applicability.md`](rust-applicability.md). Section numbers point to [`spec.md`](spec.md).

| Category (CWE-1400) | `unsafe` allowed | Safe Rust | Only via `unsafe` | Plain Rust today | Corten mechanism | Corten E / C / O / N | E verified |
| --- | ---: | ---: | ---: | --- | --- | --- | ---: |
{chr(10).join(rows)}
| **Total** | **{len(U)}** | **{len(S)}** | **{len(only)}** | | | **{b['E']} / {b['C']} / {b['O']} / {b['N']}** | **{v_all}** |

## Where Corten differs most from plain Rust

- **Injection, neutralization and file handling.** Plain Rust does nothing here; strings and paths flow freely. These are where Corten claims the most E ({inj_e} of {inj_n} injection ids, {fh_e} of {fh_n} file-handling ids), because the closed prelude removes the raw sinks.
- **Memory safety.** Plain safe Rust already prevents most of it. The gap is `unsafe` and FFI in any dependency, which plain Rust allows and cannot stop a crate author from re-enabling (spec section 10). Corten removes in-process `unsafe` and moves foreign code out of process.
- **Calculation.** Plain Rust wraps silently in release builds and truncates silently with `as`. Corten checks every operation in every profile.
- **Access control, cryptography, secrets, design.** Mostly C: Corten gives the mechanism (capabilities, evidence types, `Secret<T>`, goal-oriented crypto), but someone still has to state the policy.

## The {len(only)} weaknesses only reachable through `unsafe`

Safe Rust excludes these; they come back through `unsafe` blocks or FFI in your code or any dependency. Corten forbids application `unsafe` and in-process FFI and enforces that at the gate. Each has a program that compiles only with `unsafe` and one showing rustc rejects the safe form. Current buckets: E {sum(r['ledger_bucket'] == 'E' for r in only)}, C {sum(r['ledger_bucket'] == 'C' for r in only)}, O {sum(r['ledger_bucket'] == 'O' for r in only)}.

{", ".join(f"{r['cwe_id']} ({r['ledger_bucket']})" for r in sorted(only, key=key))}

## The {len(absent)} weaknesses that need a construct Rust does not have

{", ".join(r['cwe_id'] for r in sorted(absent, key=key))}

## The {len(notcode)} weaknesses that are not about code

{", ".join(r['cwe_id'] for r in sorted(notcode, key=key))}

## Per-CWE detail

[`rust-applicability.md`](rust-applicability.md) has every CWE with its answers, Corten status and reasoning; `rust_applicability` in [`ledger/cwe-ledger.csv`](../ledger/cwe-ledger.csv) carries the same verdict (`applies`, `unsafe-rust-only`, `not-applicable`, `not-coding`).
"""
    DOC.write_text(out)
    print(f"unsafe {len(U)} safe {len(S)} corten {len(corten)} (claims {len(corten_if_claims)}) "
          f"only-unsafe {len(only)} absent {len(absent)} not-code {len(notcode)} | baseline {base_count}: "
          f"hw {hw} absent {gone} to-safe {to_safe} to-unsafe {to_unsafe}")


if __name__ == "__main__":
    main()
